const { concatFiles } = require('./bug.cjs')
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
async function main() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'f8-'))
  const a = path.join(dir, 'a.txt')
  const b = path.join(dir, 'b.txt')
  fs.writeFileSync(a, 'A\n')
  fs.writeFileSync(b, 'B\n')
  const dst = path.join(dir, 'out.txt')
  await concatFiles(dst, [a, b])
  if (fs.readFileSync(dst, 'utf8') !== 'A\nB\n') throw new Error(`must concatenate in order, got ${JSON.stringify(fs.readFileSync(dst, 'utf8'))}`)
  await concatFiles(path.join(dir, 'single.txt'), [a])
  if (fs.readFileSync(path.join(dir, 'single.txt'), 'utf8') !== 'A\n') throw new Error('single source copies verbatim')
  await concatFiles(path.join(dir, 'empty.txt'), [])
  if (fs.readFileSync(path.join(dir, 'empty.txt'), 'utf8') !== '') throw new Error('empty source list writes an empty file')
  console.log('PASS: concatFiles joins every source in order')
}
main().then(undefined, (error) => { console.error('FAIL:', error && error.message); process.exit(1) })
